test_that("reference fits preserve blind factors and use the extracted GIC", {
  t <- seq_len(80)
  H <- cbind(first=exp(-((t-20)/5)^2),second=exp(-((t-57)/4)^2))
  X <- convMatrix(convKernel("gaussian",15L,list(sigma=2)),length(t))
  y <- round(2 + H %*% rbind(c(80,20,0),c(0,10,55)))
  run <- function(...) logconNMF(y,X,lambda="bic",family=quasipoisson("identity"),
                                 correlation="none",ncores=1L,precluster=FALSE,...)
  blind <- run()
  with <- run(truth.profiles=H)
  expect_null(blind$gic_gap)
  expect_null(blind$objective_trace)
  expect_error(gicGap(blind),"truth.profiles")
  expect_equal(fitted(with),fitted(blind),tolerance=1e-10)
  gap <- gicGap(with)
  expect_equal(gap,with$gic_gap,tolerance=1e-10)
  expect_equal(gap$fitted_gic,as.numeric(GIC(blind)))
  expect_equal(gap$percent,100*(gap$fitted_gic-gap$reference_gic)/abs(gap$reference_gic))
  p <- with$spec$information_factor*L0glm::presetLambda("gic",p=with$p,n=with$n)
  tr <- gap$trace
  expect_equal(diff(tr$GIC),diff(tr$D+p*(tr$shape_df+tr$spectral_df)),tolerance=1e-7)
  expect_equal(tail(tr$GIC[tr$start=="true profiles"],1L),gap$reference_gic)
  scaled <- run(truth.profiles=list(H=sweep(H,2,c(10,1000),"*"), id=colnames(H),
                                    area=c(0,0),P=matrix(0,2,3)))
  expect_equal(scaled$gic_gap$reference_gic,gap$reference_gic,tolerance=1e-7)
  pdf <- tempfile(fileext=".pdf")
  grDevices::pdf(pdf)
  expect_invisible(plot(gap))
  grDevices::dev.off()
  expect_gt(file.info(pdf)$size,1000)
  expect_output(print(gap),"empirical gap")
  expect_error(logconNMF(y,X,family=gaussian(),truth.profiles=H),"conditional count solver")
})

test_that("reference shapes follow samples, compound IDs and scan times", {
  t <- seq_len(40)
  H <- cbind(a=exp(-((t-13)/4)^2),b=exp(-((t-30)/3)^2),absent=0)
  truth <- list(B=list(H=H[,2:1],id=c("b","a"),time=t),A=H[6:30,,drop=FALSE])
  out <- cc_truth_profiles(truth,list(6:30,6:30),c("A","B"))
  expect_identical(out[[1]]$id,c("a","b"))
  expect_equal(as.matrix(out[[1]]$H),as.matrix(out[[2]]$H[,2:1]),ignore_attr=TRUE)
  expect_error(cc_truth_profiles(truth,list(t,t),c("A","C")),"sample IDs")
  expect_error(cc_truth_profiles(list(H=H,id=c("a","a","z")),list(t),"A"),"unique compound")
  expect_error(cc_truth_profiles(-H,list(t),"A"),"nonnegative")
  expect_error(cc_truth_profiles(list(H=H,time=t),list(t+.1),"A"),"scan times")
  expect_error(cc_truth_profiles(list(unname(H),unname(H[,1:2])),list(t,t),c("A","B")),"same columns")
  named <- cc_truth_profiles(list(H=H,B=H),list(t,t),c("B","H"))
  expect_equal(named[[1L]],named[[2L]])
  sim <- simulateGCMSSamples(samples=2L,n=120L,k=8L,presence=.5,seed=3)
  shapes <- cc_truth_profiles(sim,lapply(sim$samples,"[[","time"),
                             vapply(sim$samples,"[[","","sample_id"))
  s <- sim$samples[[1]]
  target <- s$H_true[,s$present,drop=FALSE]*s$exposure
  expect_equal(as.matrix(shapes[[1]]$H),sweep(target,2,colSums(target),"/"),ignore_attr=TRUE)
  expect_equal(shapes[[1]]$id,which(s$present))
  h <- cc_feasible_reference(shapes[[1]]$H,s$time)
  expect_silent(cc_faces(s$time,as.matrix(h),TRUE))
  expect_equal(as.numeric(Matrix::colSums(h)),rep(1,ncol(h)))
  t <- c(0,1,3,4,6)
  input <- Matrix::Matrix(cbind(c(0,4,0,1,0),exp(-abs(t-3))),sparse=TRUE)
  expected <- c(0,4,4^(1/3),1,0)
  h <- as.matrix(cc_feasible_reference(as(input,"dgCMatrix"),t))
  expect_equal(h[,1],expected/sum(expected))
  expect_equal(h[,2],as.numeric(input[,2])/sum(input[,2]))
})

test_that("matched joint reference fits accept absent compounds and reordered samples", {
  t <- seq_len(64L)
  X <- convMatrix(convKernel("gaussian",15L,list(sigma=2)),length(t))
  H <- cbind(a=exp(-((t-20)/5)^2),b=exp(-((t-43)/4)^2))
  P <- rbind(c(60,20,0),c(0,15,50))
  samples <- list(A=list(y=round(2+H%*%P),time=t,X=X),
                  B=list(y=round(2+H[,1,drop=FALSE]%*%P[1,,drop=FALSE]),time=t,X=X))
  f <- logconNMF(samples,truth.profiles=list(B=H[,1,drop=FALSE],A=H),
                 ncores=1L,precluster=FALSE,align=FALSE)
  on.exit(unlink(f$store$path,recursive=TRUE))
  d <- gicGap(f)
  ref <- subset(d$trace,start=="true profiles")
  expect_equal(ref$calls[1L],3)
  expect_equal(ref$rank[1L],2)
  expect_equal(d$fitted_gic,as.numeric(GIC(f)))
  expect_equal(readRDS(file.path(f$store$path,"model.rds"))$gic_gap,d)
})
